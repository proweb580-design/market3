export function InfoView({ page }: { page: InfoPage }) {
  return (
    <article className="px-page mx-auto max-w-3xl pt-10 pb-16">
      <p className="label-xs text-muted-foreground">Помощь</p>
      <h1 className="title-xl mt-1 text-4xl sm:text-6xl">{page.title}</h1>
      <p className="mt-4 text-sm text-muted-foreground">{page.intro}</p>
      {page.sections.map((s) => (
        <section key={s.title} className="mt-10 border-t border-border pt-6">
          <h2 className="label-xs font-bold">{s.title}</h2>
          {s.body.map((p) => (
            <p key={p} className="mt-3 text-sm leading-relaxed">
              {p}
            </p>
          ))}
        </section>
      ))}
    </article>
  );
}
